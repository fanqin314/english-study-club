chrome.runtime.onMessage.addListener((request, sender, sendResponse) => {
  if (request.action === 'detectCaptions') { sendResponse(detectYouTubeCaptions()); return true; }
  if (request.action === 'extractCaptions') {
    extractYouTubeCaptions(request.track).then(result => sendResponse(result));
    return true;
  }
  if (request.action === 'getSelectionStatus') {
    const selection = window.getSelection();
    sendResponse({ hasSelection: !!(selection && !selection.isCollapsed && selection.toString().trim().length > 0) });
    return true;
  }
});

