// Selection handlers
// ============================================================
document.addEventListener('mouseup', (e) => {
  setTimeout(() => {
    const selection = window.getSelection();
    if (!selection || selection.isCollapsed || !selection.toString().trim()) {
      if (!e.target.closest('#erl-floating-btn') && !e.target.closest('.erl-modal-mask')) {
        hideFloatingButton();
        currentSelection = null;
      }
      return;
    }
    const text = selection.toString().trim();
    if (!text) return;
    const asWord = isSingleWord(text);
    currentSelection = { text: text, isWord: asWord };
    const txtEl = floatingBtn.querySelector('.erl-btn-text');
    if (txtEl) txtEl.textContent = asWord ? '查词' : '保存到英研社';
    const range = selection.getRangeAt(0);
    const rect = range.getBoundingClientRect();
    showFloatingButton(rect.left + rect.width / 2, rect.top + window.scrollY);
  }, 10);
});

document.addEventListener('mousedown', (e) => {
  if (!e.target.closest('#erl-floating-btn') && !e.target.closest('.erl-modal-mask')) {
    const selection = window.getSelection();
    if (!selection || selection.isCollapsed) hideFloatingButton();
  }
});

