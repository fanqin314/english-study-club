// YouTube Caption Detection & Extraction
// ============================================================
function detectYouTubeCaptions() {
  try {
    const playerResponse = window.ytInitialPlayerResponse;
    if (!playerResponse || !playerResponse.captions) {
      return { success: false, error: 'No captions data found' };
    }
    const captionTracks = playerResponse.captions.playerCaptionsTracklistRenderer;
    if (!captionTracks || !captionTracks.captionTracks) {
      return { success: false, error: 'No caption tracks available' };
    }
    const tracks = captionTracks.captionTracks.map(track => ({
      name: track.name ? track.name.simpleText || track.name : 'Unknown',
      code: track.languageCode,
      url: track.baseUrl,
      kind: track.kind || '',
      autoGenerated: track.kind === 'asr' || (track.name && track.name.simpleText && track.name.simpleText.includes('auto'))
    }));
    return { success: true, tracks: tracks };
  } catch (err) {
    return { success: false, error: err.message };
  }
}

async function extractYouTubeCaptions(track) {
  try {
    const response = await fetch(track.url);
    const xmlText = await response.text();
    const parser = new DOMParser();
    const xmlDoc = parser.parseFromString(xmlText, 'text/xml');
    if (xmlDoc.querySelector('parsererror')) {
      return { success: false, error: 'Failed to parse caption XML' };
    }
    const texts = xmlDoc.querySelectorAll('text');
    const lines = [];
    texts.forEach(el => {
      const text = el.textContent || '';
      const cleaned = text.replace(/<[^>]+>/g, '').replace(/&#39;/g, "'").replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').trim();
      if (cleaned) lines.push(cleaned);
    });
    const fullText = lines.join('\n');
    let videoTitle = '';
    try {
      const pr = window.ytInitialPlayerResponse;
      if (pr && pr.videoDetails) videoTitle = pr.videoDetails.title || '';
    } catch (e) { /* ignore */ }
    if (!videoTitle) videoTitle = document.title.replace(' - YouTube', '').trim();
    return { success: true, text: fullText, videoTitle: videoTitle, url: track.url, capturedAt: formatLocalDateTime(new Date()) };
  } catch (err) {
    return { success: false, error: err.message };
  }
}

// ============================================================
// 网页端 companion 通信（postMessage 协议）
// ============================================================
const ESC_COMPANION = (function () {
  let reqSeq = 0;
  const pending = {};
  let ready = false;

  function onMessage(ev) {
    const msg = ev.data;
    if (!msg || msg.source !== 'esc-web-companion') return;
    if (msg.type === 'esc_ready') { ready = true; return; }
    if (msg.type === 'esc_response' && pending[msg.reqId]) {
      const cb = pending[msg.reqId];
      delete pending[msg.reqId];
      cb(msg);
    }
  }

  function init() {
    window.addEventListener('message', onMessage);
  }

  // 发送请求并等待响应（带超时）
  function request(action, payload, timeout = 4000) {
    return new Promise((resolve) => {
      const reqId = 'esc' + (++reqSeq) + '_' + Date.now();
      const timer = setTimeout(() => {
        if (pending[reqId]) { delete pending[reqId]; resolve({ ok: false, error: '网页端未响应（companion 未就绪）', timeout: true }); }
      }, timeout);
      pending[reqId] = (res) => { clearTimeout(timer); resolve(res); };
      window.postMessage({ source: 'esc-browser-ext', type: 'esc_request', action: action, reqId: reqId, payload: payload || {} }, '*');
    });
  }

  return {
    init,
    isReady: () => ready,
    getNotebooks: () => request('esc_getNotebooks'),
    createNotebook: (name) => request('esc_createNotebook', { name }),
    addWord: (notebookId, wordData) => request('esc_addWord', { notebookId, wordData }),
    getApiConfig: () => request('esc_getApiConfig'),
  };
})();

// 暴露给 translate.js（同 content script 上下文内共享）
window.ESC_COMPANION = ESC_COMPANION;

