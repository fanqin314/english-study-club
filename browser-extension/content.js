function showSelectionModal() {
  if (!selectionModal) createSelectionModal();
  if (!currentSelection) return;

  const preview = document.getElementById('erl-modal-preview');
  const text = currentSelection.text;
  preview.textContent = text.length > 200 ? text.slice(0, 200) + '...' : text;

  document.getElementById('erl-modal-tag').value = '';
  document.getElementById('erl-modal-save').disabled = false;
  selectionModal.classList.add('show');

  hideFloatingButton();
}

function hideSelectionModal() {
  if (selectionModal) {
    selectionModal.classList.remove('show');
  }
}

function hideFloatingButton() {
  if (floatingBtn) {
    floatingBtn.classList.remove('show');
  }
}

function showFloatingButton(x, y) {
  if (!floatingBtn) createFloatingButton();

  const btnWidth = 140;
  const btnHeight = 36;
  const margin = 10;

  let left = x + margin;
  let top = y - btnHeight - margin;

  if (left + btnWidth > window.innerWidth - 10) {
    left = window.innerWidth - btnWidth - 10;
  }
  if (top < 10) {
    top = y + margin;
  }
  if (left < 10) left = 10;

  floatingBtn.style.left = left + 'px';
  floatingBtn.style.top = top + 'px';
  floatingBtn.classList.add('show');
}

// 组装文章划线保存的 Markdown 内容
function buildArticleMd(time, tag, text) {
  return [
    '# ' + (document.title || ''),
    '',
    '- 来源: ' + window.location.href,
    '- 保存时间: ' + formatLocalDateTime(time),
    '- 标签: ' + (tag || ''),
    '',
    '> ' + text
  ].join('\n');
}

async function saveSelection() {
  if (!currentSelection) return;

  const saveBtn = document.getElementById('erl-modal-save');
  const tag = document.getElementById('erl-modal-tag').value.trim();
  // 防重入：保存期间禁用按钮
  saveBtn.disabled = true;
  saveBtn.textContent = '保存中...';

  try {
    const now = new Date();
    const filename = 'article_' + formatLocalFileStamp(now) + '.md';
    const content = buildArticleMd(now, tag, currentSelection.text);

    const connected = await checkNativeHost();

    if (connected) {
      await chrome.runtime.sendMessage({
        action: 'write',
        path: 'browser-captures/' + filename,
        content: content
      });
    } else {
      downloadFallback(filename, content, 'text/markdown;charset=utf-8');
    }

    hideSelectionModal();
    currentSelection = null;
  } catch (err) {
    try {
      // Native Host 写入失败时回退为浏览器下载（同样生成 .md 文件）
      const now = new Date();
      const filename = 'article_' + formatLocalFileStamp(now) + '.md';
      downloadFallback(filename, buildArticleMd(now, tag, currentSelection.text), 'text/markdown;charset=utf-8');
      hideSelectionModal();
      currentSelection = null;
    } catch (e2) {
      alert('保存失败: ' + err.message);
    }
  } finally {
    saveBtn.disabled = false;
    saveBtn.textContent = '保存';
  }
}

async function checkNativeHost() {
  try {
    const response = await chrome.runtime.sendMessage({ action: 'ping' });
    return response && response.connected;
  } catch (e) {
    return false;
  }
}

function downloadFallback(filename, content, mimeType) {
  const blob = new Blob([content], { type: mimeType || 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

// Mouseup handler for text selection
document.addEventListener('mouseup', (e) => {
  setTimeout(() => {
    const selection = window.getSelection();
    if (!selection || selection.isCollapsed || !selection.toString().trim()) {
      // Don't hide if clicking inside our own UI
      if (!e.target.closest('#erl-floating-btn') && !e.target.closest('#erl-selection-modal')) {
        hideFloatingButton();
        currentSelection = null;
      }
      return;
    }

    const text = selection.toString().trim();
    if (!text) return;

    currentSelection = { text: text };

    const range = selection.getRangeAt(0);
    const rect = range.getBoundingClientRect();
    const x = rect.left + rect.width / 2;
    const y = rect.top + window.scrollY;

    showFloatingButton(x, y);
  }, 10);
});

// Hide floating button when clicking elsewhere
document.addEventListener('mousedown', (e) => {
  if (!e.target.closest('#erl-floating-btn') && !e.target.closest('#erl-selection-modal')) {
    const selection = window.getSelection();
    if (!selection || selection.isCollapsed) {
      hideFloatingButton();
    }
  }
});

// ============================================================
// Message Listener
// ============================================================

chrome.runtime.onMessage.addListener((request, sender, sendResponse) => {
  if (request.action === 'detectCaptions') {
    const result = detectYouTubeCaptions();
    sendResponse(result);
    return true;
  }

  if (request.action === 'extractCaptions') {
    extractYouTubeCaptions(request.track).then(result => {
      sendResponse(result);
    });
    return true;
  }

  if (request.action === 'getSelectionStatus') {
    const selection = window.getSelection();
    const hasSelection = selection && !selection.isCollapsed && selection.toString().trim().length > 0;
    sendResponse({ hasSelection: hasSelection });
    return true;
  }
});

// Initialize on load
(function init() {
  createFloatingButton();
  createSelectionModal();
})();
