// ============================================================
// Local time helpers (本地时间，不使用 toISOString 避免时区偏差)
// ============================================================

function pad2(n) {
  return n < 10 ? '0' + n : '' + n;
}

// 本地时间 → YYYY-MM-DD HH:mm:ss
function formatLocalDateTime(d) {
  return d.getFullYear() + '-' + pad2(d.getMonth() + 1) + '-' + pad2(d.getDate()) +
    ' ' + pad2(d.getHours()) + ':' + pad2(d.getMinutes()) + ':' + pad2(d.getSeconds());
}

// 本地时间 → YYYYMMDD_HHmmss（用于文件名）
function formatLocalFileStamp(d) {
  return d.getFullYear() + pad2(d.getMonth() + 1) + pad2(d.getDate()) +
    '_' + pad2(d.getHours()) + pad2(d.getMinutes()) + pad2(d.getSeconds());
}

// ============================================================
// YouTube Caption Detection & Extraction
// ============================================================

function detectYouTubeCaptions() {
  try {
    const playerResponse = window.ytInitialPlayerResponse;
    if (!playerResponse || !playerResponse.captions) {
      return { success: false, error: 'No captions data found' };
    }

    const captionTracks = playerResponse.captions.playerCaptionsTracklistRenderer;
    if (!captionTracks || !captionTracks.captionTracks) {
      return { success: false, error: 'No caption tracks available' };
    }

    const tracks = captionTracks.captionTracks.map(track => ({
      name: track.name ? track.name.simpleText || track.name : 'Unknown',
      code: track.languageCode,
      url: track.baseUrl,
      kind: track.kind || '',
      autoGenerated: track.kind === 'asr' || (track.name && track.name.simpleText && track.name.simpleText.includes('auto'))
    }));

    return { success: true, tracks: tracks };
  } catch (err) {
    return { success: false, error: err.message };
  }
}

async function extractYouTubeCaptions(track) {
  try {
    const response = await fetch(track.url);
    const xmlText = await response.text();

    const parser = new DOMParser();
    const xmlDoc = parser.parseFromString(xmlText, 'text/xml');

    if (xmlDoc.querySelector('parsererror')) {
      return { success: false, error: 'Failed to parse caption XML' };
    }

    const texts = xmlDoc.querySelectorAll('text');
    const lines = [];
    texts.forEach(el => {
      const text = el.textContent || '';
      const cleaned = text.replace(/<[^>]+>/g, '').replace(/&#39;/g, "'").replace(/&amp;/g, '&').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/&quot;/g, '"').trim();
      if (cleaned) {
        lines.push(cleaned);
      }
    });

    const fullText = lines.join('\n');

    let videoTitle = '';
    try {
      const playerResponse = window.ytInitialPlayerResponse;
      if (playerResponse && playerResponse.videoDetails) {
        videoTitle = playerResponse.videoDetails.title || '';
      }
    } catch (e) { /* ignore */ }

    if (!videoTitle) {
      videoTitle = document.title.replace(' - YouTube', '').trim();
    }

    // 返回结构约定：popup 端负责组装 MD（含 # 标题、- 来源、- 提取时间、正文）
    return {
      success: true,
      text: fullText,
      videoTitle: videoTitle,
      url: track.url,
      capturedAt: formatLocalDateTime(new Date())
    };
  } catch (err) {
    return { success: false, error: err.message };
  }
}

