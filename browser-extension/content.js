async function openLookupModal(word) {
  if (!lookupModal) createLookupModal();
  lookupModal.classList.add('show');
  hideFloatingButton();
  const wEl = document.getElementById('erl-lookup-word');
  const posEl = document.getElementById('erl-lookup-pos');
  const defEl = document.getElementById('erl-lookup-def');
  const exEl = document.getElementById('erl-lookup-ex');
  const metaEl = document.querySelector('#erl-lookup-modal .erl-lookup-meta');
  const statusEl = lookupModal.querySelector('.erl-status');
  wEl.innerHTML = '<span>' + escapeHtml(word) + '</span>';
  posEl.textContent = ''; defEl.textContent = ''; exEl.textContent = ''; metaEl.textContent = '';
  statusEl.className = 'erl-status'; statusEl.textContent = '';
  defEl.className = 'erl-loading'; defEl.textContent = '查词中…';
  lookupModal.querySelector('.erl-lookup-add').disabled = true;

  const settings = await window.ESCStore.getSettings();
  let res;
  try {
    res = await window.ESCTranslate.lookup(word, { settings });
  } catch (e) {
    res = { word: word, phonetic: '', pos: '', definition: '查词失败：' + (e.message || e), example: '', source: '?' };
  }
  lookupResult = res;
  defEl.className = 'erl-lookup-def';
  wEl.innerHTML = '<span>' + escapeHtml(res.word || word) + '</span>' +
    (res.phonetic ? '<span id="erl-lookup-phonetic">/' + escapeHtml(res.phonetic) + '/</span>' : '');
  posEl.textContent = res.pos || '';
  defEl.textContent = res.definition || '（无释义）';
  exEl.textContent = res.example || '';
  metaEl.textContent = '来源：' + sourceLabel(res.source) + (res.source === 'A' ? '（魔塔 AI）' : '（本地词库）');
  lookupModal.querySelector('.erl-lookup-add').disabled = false;

  // 加载生词本列表（优先网页端 companion，回退本地）
  await loadNotebookOptions();
}

function sourceLabel(s) {
  if (s === 'A') return '魔塔 AI';
  if (s === 'B') return '本地词库';
  if (s && s.indexOf('降级') >= 0) return '本地词库（降级）';
  return s || '—';
}

function hideLookupModal() { if (lookupModal) lookupModal.classList.remove('show'); }

// 加载笔记本下拉：先问网页端 companion，失败/超时回退插件本地
async function loadNotebookOptions() {
  const sel = lookupModal.querySelector('.erl-notebook-select');
  sel.innerHTML = '<option value="">加载生词本…</option>';
  let webNotebooks = [];
  try {
    const r = await ESC_COMPANION.getNotebooks();
    if (r && r.ok && r.data && r.data.notebooks) {
      webNotebooks = r.data.notebooks;
    }
  } catch (e) { /* 忽略，走本地回退 */ }

  if (webNotebooks.length > 0) {
    sel.innerHTML = '';
    const hint = document.createElement('option');
    hint.disabled = true; hint.textContent = '— 网页端生词本 —';
    sel.appendChild(hint);
    webNotebooks.forEach(function (nb) {
      const o = document.createElement('option');
      o.value = 'web:' + nb.id;
      o.textContent = nb.name + '（' + nb.count + '）';
      sel.appendChild(o);
    });
    const o2 = document.createElement('option');
    o2.value = 'local:__esc_local__';
    o2.textContent = '— 仅存浏览器插件 —';
    sel.appendChild(o2);
  } else {
    sel.innerHTML = '<option value="local:__esc_local__">浏览器插件生词本（网页端未打开）</option>';
  }
}

function onNewNotebook() {
  const box = lookupModal.querySelector('.erl-newbook');
  box.classList.toggle('show');
  if (box.classList.contains('show')) {
    const input = lookupModal.querySelector('.erl-newbook-input');
    input.focus();
    input.onkeydown = function (e) {
      if (e.key === 'Enter') createNewNotebookFromLookup();
    };
  }
}

async function createNewNotebookFromLookup() {
  const input = lookupModal.querySelector('.erl-newbook-input');
  const name = (input.value || '').trim();
  if (!name) return;
  const statusEl = lookupModal.querySelector('.erl-status');
  statusEl.className = 'erl-status'; statusEl.textContent = '新建中…';
  try {
    const r = await ESC_COMPANION.createNotebook(name);
    if (r && r.ok && r.data && r.data.id) {
      await loadNotebookOptions();
      const sel = lookupModal.querySelector('.erl-notebook-select');
      sel.value = 'web:' + r.data.id;
      statusEl.className = 'erl-status ok'; statusEl.textContent = '已新建《' + name + '》';
      lookupModal.querySelector('.erl-newbook').classList.remove('show');
      input.value = '';
      return;
    }
    statusEl.className = 'erl-status warn'; statusEl.textContent = (r && r.error) ? ('新建失败：' + r.error) : '网页端未打开，已存为插件生词本';
    // 回退：以插件本地存储记录（用 notebook 名）
    const sel = lookupModal.querySelector('.erl-notebook-select');
    sel.innerHTML = '<option value="local:__esc_local__">浏览器插件生词本（网页端未打开）</option>';
    sel.value = 'local:__esc_local__';
  } catch (e) {
    statusEl.className = 'erl-status warn'; statusEl.textContent = '网页端未响应，将存为插件生词本';
  }
}

async function addLookupWord() {
  if (!lookupResult) return;
  const sel = lookupModal.querySelector('.erl-notebook-select');
  const val = sel.value || 'local:__esc_local__';
  const statusEl = lookupModal.querySelector('.erl-status');
  const addBtn = lookupModal.querySelector('.erl-lookup-add');
  addBtn.disabled = true;

  const wordData = {
    word: lookupResult.word,
    phonetic: lookupResult.phonetic || '',
    definition: lookupResult.definition || '',
    example: lookupResult.example || '',
    pos: lookupResult.pos || '',
    context: '',
    timestamp: Date.now(),
  };

  // 1) 尝试实时写入网页端（companion）
  if (val.indexOf('web:') === 0) {
    const nbId = val.slice(4);
    const nbName = sel.options[sel.selectedIndex] ? sel.options[sel.selectedIndex].textContent.split('（')[0] : '网页端';
    statusEl.className = 'erl-status'; statusEl.textContent = '正在加入《' + nbName + '》…';
    const r = await ESC_COMPANION.addWord(nbId, wordData);
    if (r && r.ok) {
      statusEl.className = 'erl-status ok';
      statusEl.textContent = '已加入网页端《' + nbName + '》';
      setTimeout(hideLookupModal, 700);
      addBtn.disabled = false;
      return;
    }
    // 失败：回退存插件本地
    await window.ESCStore.addVocab(Object.assign({}, wordData, { notebook: nbName }));
    statusEl.className = 'erl-status warn';
    statusEl.textContent = '网页端未响应，已存入浏览器插件生词本《' + nbName + '》';
    setTimeout(hideLookupModal, 900);
    addBtn.disabled = false;
    return;
  }

  // 2) 仅存浏览器插件本地
  await window.ESCStore.addVocab(Object.assign({}, wordData, { notebook: 'default' }));
  statusEl.className = 'erl-status ok';
  statusEl.textContent = '已存入浏览器插件生词本';
  setTimeout(hideLookupModal, 700);
  addBtn.disabled = false;
}

function escapeHtml(s) {
  return String(s == null ? '' : s)
    .replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

// ---------- 划线保存 ----------
function buildArticleMd(time, tag, text) {
  return [
    '# ' + (document.title || ''),
    '',
    '- 来源: ' + window.location.href,
    '- 保存时间: ' + formatLocalDateTime(time),
    '- 标签: ' + (tag || ''),
    '',
    '> ' + text
  ].join('\n');
}

async function saveSelection() {
  if (!currentSelection) return;
  const saveBtn = saveModal.querySelector('.erl-save-go');
  const tag = saveModal.querySelector('.erl-save-tag').value.trim();
  saveBtn.disabled = true; saveBtn.textContent = '保存中...';
  try {
    const now = new Date();
    const stamp = formatLocalFileStamp(now);
    const filename = 'article_' + stamp + '.md';
    const content = buildArticleMd(now, tag, currentSelection.text);
    if (window.ESCStore) {
      await window.ESCStore.addCapture({
        id: 'cap_' + stamp,
        title: document.title || '网页采集',
        text: currentSelection.text,
        url: window.location.href,
        source: 'selection',
        createdAt: window.ESCStore.nowIso(),
      });
    }
    // 优先写入已选定的本地文件夹；未选定或失败则回退下载兜底。
    const written = await writeToFolder(filename, content);

    if (!written) {
      // 回退：下载兜底（仅当未选定文件夹时主动触发；选定但写入失败也兜底）
      try {
        const now = new Date();
        downloadFallback('article_' + formatLocalFileStamp(now) + '.md', content, 'text/markdown;charset=utf-8');
      } catch (dlErr) { /* 下载失败不阻断本地存储 */ }
    }
    hideSaveModal();
    currentSelection = null;
  } catch (err) {
    try {
      const now = new Date();
      downloadFallback('article_' + formatLocalFileStamp(now) + '.md', buildArticleMd(now, tag, currentSelection.text), 'text/markdown;charset=utf-8');
      hideSaveModal();
      currentSelection = null;
    } catch (e2) {
      alert('保存失败: ' + err.message);
    }
  } finally {
    saveBtn.disabled = false; saveBtn.textContent = '保存';
  }
}

