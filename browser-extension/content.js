// ============================================================
// 本地文件夹缓存（File System Access API）
// 在页面内触发 showDirectoryPicker，把 DirectoryHandle 存入
// chrome.storage.session（结构化克隆可存 FileSystemHandle）。
// 之后采集/字幕优先写入该文件夹，失败回退 chrome.storage.local + 下载。
// ============================================================
async function getFolderHandle() {
  try {
    const s = await chrome.storage.session.get('escFolder');
    if (s.escFolder && s.escFolder.handle) {
      // 跨页面/跨时间权限可能失效，先验证
      try {
        const perm = await s.escFolder.handle.queryPermission({ mode: 'readwrite' });
        if (perm !== 'granted') {
          const req = await s.escFolder.handle.requestPermission({ mode: 'readwrite' });
          if (req !== 'granted') return null;
        }
        return s.escFolder.handle;
      } catch (e) { return null; }
    }
  } catch (e) { /* ignore */ }
  return null;
}

// 写入本地文件夹。成功返回 true；无文件夹或失败返回 false（调用方需回退）。
async function writeToFolder(filename, content) {
  const handle = await getFolderHandle();
  if (!handle) return false;
  try {
    const fileHandle = await handle.getFileHandle(filename, { create: true });
    const writable = await fileHandle.createWritable();
    await writable.write(content);
    await writable.close();
    return true;
  } catch (e) {
    return false;
  }
}

function downloadFallback(filename, content, mimeType) {
  const blob = new Blob([content], { type: mimeType || 'text/plain;charset=utf-8' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url; a.download = filename;
  document.body.appendChild(a); a.click(); document.body.removeChild(a);
  URL.revokeObjectURL(url);
}

// ---------- 浮动按钮显示 ----------
function hideFloatingButton() { if (floatingBtn) floatingBtn.classList.remove('show'); }
function showFloatingButton(x, y) {
  if (!floatingBtn) createFloatingButton();
  const btnWidth = 140, btnHeight = 36, margin = 10;
  let left = x + margin, top = y - btnHeight - margin;
  if (left + btnWidth > window.innerWidth - 10) left = window.innerWidth - btnWidth - 10;
  if (top < 10) top = y + margin;
  if (left < 10) left = 10;
  floatingBtn.style.left = left + 'px';
  floatingBtn.style.top = top + 'px';
  floatingBtn.classList.add('show');
}

