// Local time helpers
// ============================================================
function pad2(n) {
  return n < 10 ? '0' + n : '' + n;
}
function formatLocalDateTime(d) {
  return d.getFullYear() + '-' + pad2(d.getMonth() + 1) + '-' + pad2(d.getDate()) +
    ' ' + pad2(d.getHours()) + ':' + pad2(d.getMinutes()) + ':' + pad2(d.getSeconds());
}
function formatLocalFileStamp(d) {
  return d.getFullYear() + pad2(d.getMonth() + 1) + pad2(d.getDate()) +
    '_' + pad2(d.getHours()) + pad2(d.getMinutes()) + pad2(d.getSeconds());
}

// ============================================================
// 接收网页端本地文件夹连接状态广播（core/local_file_storage.js 发出）
// 仅含文件夹名，不含句柄。存入 chrome.storage.session 供 popup 读取，
// 实现「网页端已选文件夹 → 插件显示已对齐」的感知。
// ============================================================
window.addEventListener('message', (event) => {
  try {
    const data = event.data;
    if (!data || data.source !== 'esc-web-folder') return;
    chrome.storage.session.set({
      escWebFolder: { active: !!data.active, name: data.name || '' }
    });
  } catch (e) { /* ignore */ }
});

// content script 注入后立即请求页面重发一次文件夹状态，
// 覆盖「页面 init 广播早于本监听注册」的漏广播时序问题。
try {
  window.postMessage({ source: 'esc-web-req-folder' }, '*');
} catch (e) { /* ignore */ }

// 响应 popup 的「请让网页端重发文件夹状态」请求（popup 打开时主动触发）
try {
  chrome.runtime.onMessage.addListener((msg, sender, sendResponse) => {
    if (msg && msg.action === 'requestWebFolderState') {
      try {
        window.postMessage({ source: 'esc-web-req-folder' }, '*');
      } catch (e) { /* ignore */ }
      // 主动读一次当前已存的 web 状态并回传给 popup（避免 popup 还需等延迟）
      chrome.storage.session.get('escWebFolder', (s) => {
        sendResponse({ escWebFolder: s && s.escWebFolder ? s.escWebFolder : null });
      });
      return true; // 异步 sendResponse
    }
  });
} catch (e) { /* ignore */ }

